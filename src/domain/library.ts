function h(
  id: string,
  title: string,
  factorKind: Hazard["factorKind"],
  source: string,
  event: string,
  ppeIds: string[],
  measures: [string, string[]][],
): Hazard {
  return {
    meta: meta({ id, title }),
    source,
    event,
    factorKind,
    ppeIds,
    measures: pts(id, measures),
  };
}

export const risks: Risk[] = hazards.map((item) => ({
  meta: meta({
    id: `risk_${item.meta.id}`,
    title: `Риск: ${item.event.toLowerCase()}`,
  }),
  hazardId: item.meta.id,
  consequence: item.event,
  level: item.factorKind === "dangerous" ? "высокий" : "умеренный",
  controls: item.measures.map((point) => point.text).join(" "),
}));

